ふたりの暮らしを1つにまとめたアプリ。買い物・在庫・レシピ・予定・家計を扱う。

困ったら、いつでもこの画面に戻ってきてください。
ホームの右上「使い方」か、買い物タブの「⋮」→「使い方」で開けます。

