下の「ほかの画面」から、**タブに置いていない画面すべて**に行けます。
やること・家事の設定・予定のタグ・資産と負債・投資・レシピ・使い方。
「あの設定どこだっけ」と迷ったら、まずホームを開いてください。

サインアウトもここです。

