-- ============================================================
-- schema_v6.sql — 在庫の「置き場所」を 3 区分から 5 区分へ広げる
--
-- 【このファイルは何か】
--   inventory.location が取れる値を、いまの
--       冷蔵 / 冷凍 / 常温
--   から
--       冷蔵 / 氷温 / 野菜 / 冷凍 / 常温
--   に差し替え、すでに入っている 18 行を新しい区画へ振り分ける。
--
-- 【いつ実行するか】
--   Supabase の SQL Editor に【全文を貼って一度に実行】する。
--   (途中だけ選んで実行すると begin/commit が分断されるので必ず全文)
--   psql からでもよい。アプリからは実行しない(RLS の外側の作業なので、
--   SQL Editor の権限で流す必要がある)。
--
--   実行の順番は下の「デプロイの順番」を必ず読むこと。
--   SQL とアプリのどちらを先に出すかで、見え方が変わる。
--
-- 【前提】
--   schema.sql(初回)〜 schema_v5.sql まで適用済みの本番データベース。
--   inventory は 18 行(冷蔵 11 / 冷凍 5 / 常温 2)。2026-08-09 に実測。
-- ============================================================


-- ============================================================
-- なぜこの 5 区画なのか
-- ============================================================
--
-- 【大前提: これはこの家の冷蔵庫の形である。一般的な分類ではない】
--
--   実機は 日立 R-HWC54Y(定格内容積 540L・6 ドア・まるごとチルド)。
--   区画とその容積・温度は取扱説明書 p.19 / p.49 の値。
--
--     冷蔵室            278L   約 0〜3℃(まるごとチルド設定時・棚)
--       └ 特鮮氷温ルーム  14L   約 -2〜0℃
--     野菜室            103L   約 4〜8℃(たて収納スペースのみ 4〜9℃)
--     冷凍室 上段        28L   約 -19〜-17℃(★★ 表示)
--     冷凍室 下段       109L   約 -20〜-18℃(★★★★ 表示)
--     製氷室             22L
--
--   つまり「冷蔵 / 冷凍 / 常温」の 3 つでは、扉を開けたときの実物と
--   アプリの表示が一致しない。氷温ルームと野菜室という【温度帯の違う
--   独立した引き出し】が、どちらも「冷蔵」に潰れていた。
--   きゅうりも 6P チーズも同じ「冷蔵」と表示されるが、実際の置き場所は
--   4〜8℃ の野菜室と 0〜3℃ の棚で、温度が 5℃ 以上違う。
--
--   ★ 冷蔵庫を買い替えたら、この区画分けは意味を失う。
--     そのときは最後の「元に戻す手順」を使うこと。
--
-- 【区画をこの 5 つに決めた理由】
--
--   ・冷蔵(冷蔵室の棚・まるごとチルド 約 0〜3℃)
--       乳製品・卵・豆腐・納豆・惣菜・作り置き。
--   ・氷温(特鮮氷温ルーム 約 -2〜0℃)
--       肉・魚・練り物。凍らせずに冷蔵より長持ちする。
--       乳製品・豆腐・こんにゃく・ゆで卵・カット野菜は入れない
--       (凍ってスが入る/風味が落ちる。取説 p.24)。
--   ・野菜(新鮮スリープ野菜室 約 4〜8℃・高湿度)
--       葉物・根菜・使いかけの野菜。うるおいユニットで乾燥しにくい。
--   ・冷凍(冷凍室 上段/下段)
--       上段と下段は星の数が違う(★★ と ★★★★)が、アプリでは
--       分けない。理由は下の「分けなかったもの」を参照。
--   ・常温(冷暗所)
--       玉ねぎ・じゃがいも・さつまいも・かぼちゃ(丸ごと)、
--       未開封の調味料・乾物。
--
-- 【あえて分けなかったもの】
--
--   ・冷凍上段 / 冷凍下段 を 1 つの「冷凍」にまとめた。
--     実機では別物(上段 ★★ は長期保存に向かない)だが、区画を 6 つに
--     すると在庫画面のタブが 1 つ 55px まで細くなり、濡れた手で押せない。
--     どちらの段に入れたかは、実害が出たら memo で足りる。
--   ・ドアポケット(約 0〜7℃)を独立させなかった。
--     温度帯としては第 6 の帯だが、入るのは調味料と飲み物で、
--     アプリで在庫管理する対象がほぼ無い。
--   ・製氷室は食品を置かないので対象外。
--
-- 【なぜ 2 文字の短い名前なのか】
--
--   この値は在庫画面のタブの文字にそのまま出る。
--   幅 390px(iPhone 14)で 5 分割すると 1 タブ 66.8px しかない。
--   「うるおい野菜室」は 14px × 7 文字 = 98px で入りきらず、2 行に折れて
--   pill の白い箱からはみ出す。全部 2 文字に揃えると 28px + 件数で
--   45.2px に収まり、余白 21.6px が残る。
--   → 正式名(氷温ルーム/うるおい野菜室)は画面側の対応表で持ち、
--     データベースには短い方だけを入れる。
--
--   ★★★ この 5 つの文字列は lib/types.ts:40 の LOCATIONS と
--        【1 文字も違わず同じ】でなければならない。 ★★★
--        アプリは lib/inventory-store.ts:189 で location をそのまま送る。
--        値がずれると Postgres が 23514(check 制約違反)を返し、
--        lib/inventory-store.ts:156-159 がそれを「拒否」と判断して
--        その操作を【黙って 1 件捨てる】。ユーザーには何も出ない。
--        表記ゆれ(「野菜室」と「野菜」など)は事故に直結する。
--
-- ============================================================
-- デプロイの順番(ここを間違えると在庫が消えたように見える)
-- ============================================================
--
--   1. 先に【この SQL の Part 1 だけ】を流す。
--      → 制約が 5 値を許すようになるだけで、データは 1 行も動かない。
--        古いアプリ(3 タブ)はそのまま何事もなく動き続ける。
--
--   2. 次にアプリを出す。
--      lib/types.ts:40 の LOCATIONS を 5 値に、
--      public/sw.js:12 の VERSION を v14 から上げる
--      (上げないと古い端末に古い画面が残り続ける)。
--
--   3. 2 台のスマホでアプリを開き直し、5 タブになったことを確認してから
--      【Part 2】を流す。
--
--   ▲ なぜこの順番か
--     Part 2 を先に流すと、きゅうり・小松菜・長ねぎ・人参の 4 行が
--     location='野菜' になる。3 タブのままの端末は
--     components/InventoryScreen.tsx:105 で
--         items.filter((i) => i.location === tab)
--     と絞り込むので、'野菜' はどのタブにも一致せず
--     【4 行がどこにも出てこない】= 在庫が消えたように見える。
--     データは無事だが、冷蔵庫の前で在庫を見ている人には区別が付かない。
--
--   ▲ 急ぐとき
--     Part 1 だけで止めても、データベースは完全に正しい状態で止まる。
--     Part 2 は後日でよい。Part 1 と Part 2 は別々のトランザクションに
--     分けてあるので、間で止めても中途半端な状態は残らない。


-- ============================================================
-- Part 1 — 制約の入れ替え(データは動かさない)
-- ============================================================
--
-- 【なぜ「外す → 直す → 付ける」の順なのか】
--
--   古い制約 check (location in ('冷蔵','冷凍','常温')) が付いたままだと、
--   location に '野菜' を書き込もうとした瞬間に 23514 で弾かれる。
--   だから【必ず古い制約を先に外す】。外す前にデータを直そうとすると、
--   1 行目の update で失敗して何も進まない。
--
--   逆に、新しい制約を先に付けるのも駄目。制約を追加するとき Postgres は
--   既存の全行を検査するので、1 行でも外れた値があると
--   【追加そのものが失敗して、表全体が古い制約のまま取り残される】。
--   だから制約を付けるのは、値をすべて安全側に寄せた後にする。
--
-- 【この表に限っては、実は付ける順でも失敗しない。それでもこの順にする】
--
--   新しい 5 値は古い 3 値を丸ごと含んでいる(冷蔵・冷凍・常温はどれも
--   新しい方にも入っている)。つまり今ある 18 行はすべて新しい制約でも
--   合格するので、理屈の上では先に付けても通る。
--   それでも「外す → 直す → 付ける」にしているのは、
--   想定していない値(手作業で入れた値、将来の別の作業が入れた値)が
--   1 行でもあったときに、この SQL が途中で止まらないようにするため。
--   下の「保険」がその 1 行を拾って '冷蔵' に寄せてから制約を付けるので、
--   何が入っていても Part 1 は必ず最後まで通る。

begin;

-- ------------------------------------------------------------
-- 1-1. 古い制約を外す
-- ------------------------------------------------------------
-- 制約の名前は schema.sql:59-60 で明示していないため Postgres が
-- 自動で付けている(たぶん inventory_location_check)。
-- 名前を決め打ちすると、違う名前だったときに黙って何も外れず、
-- 後続の update が 23514 で落ちる。
-- なので【名前で探さず、location を見ている check 制約を全部外す】。
--
-- この書き方には、もう 1 つ利点がある。
-- 2 回目にこのファイルを流したとき、1-3 で付けた新しい制約も
-- ここで一度外れるので、1-3 の add constraint が
-- 「同じ名前が既にある」で落ちない。= 何度流しても通る。
do $$
declare c record;
begin
  for c in
    select conname
      from pg_constraint
     where conrelid = 'public.inventory'::regclass
       and contype = 'c'                                  -- c = check 制約
       and pg_get_constraintdef(oid) like '%location%'
  loop
    execute format('alter table public.inventory drop constraint %I', c.conname);
    raise notice '古い制約を外しました: %', c.conname;
  end loop;
end $$;

-- ------------------------------------------------------------
-- 1-2. 保険 — 新しい 5 値のどれでもない行を '冷蔵' に寄せる
-- ------------------------------------------------------------
-- 実測では該当 0 行。それでも書いておく理由は 2 つ。
--
--   ・1 行でも外れた値があると 1-3 の制約追加が失敗し、
--     inventory が制約なしのまま放置される。それが一番まずい。
--     ここで全部を安全な値に寄せておけば、1-3 は必ず成功する。
--   ・寄せ先を '冷蔵' にしたのは、schema.sql:59 の既定値が '冷蔵' で、
--     在庫画面の最初に開くタブも「冷蔵」だから。
--     どこかに紛れて見えなくなるより、最初に目に入る場所へ出す。
--
-- location は not null 列なので null は原理上あり得ないが、
-- 過去に誰かが not null を外していた場合に備えて null も拾う。
update inventory
   set location = '冷蔵'
 where location is null
    or location not in ('冷蔵', '氷温', '野菜', '冷凍', '常温');

-- ------------------------------------------------------------
-- 1-3. 新しい制約を付ける
-- ------------------------------------------------------------
-- 並び順は【冷蔵庫の上から下】。在庫画面のタブもこの順に並べる。
-- 冷蔵(上段の棚) → 氷温(冷蔵室の中の引き出し) → 野菜 → 冷凍 → 常温。
-- 制約自体は順番を見ないが、ここを読んだ人が画面の並びを迷わないように
-- 揃えておく。
--
-- 名前を inventory_location_check と明示しているのは、
-- 2 回目以降に 1-1 が確実に見つけて外せるようにするため。
alter table inventory
  add constraint inventory_location_check
  check (location in ('冷蔵', '氷温', '野菜', '冷凍', '常温'));

-- 既定値は '冷蔵' のまま変えない。
--   新しく買ってきた物をアプリ以外の経路で入れたとき、
--   最初に開くタブに出るのが一番親切だから。
-- schema.sql:134 の index (household_id, location) も変えなくてよい。
--   値の種類が 3 から 5 に増えるだけで、索引の作り方は同じ。

commit;


-- ============================================================
-- Part 2 — いまの 18 行を新しい区画へ振り分ける
-- ============================================================
--
-- 【方針: このスクリプトは「棚を貼り替える」だけで、「食べ物を運ばない」】
--
--   データベースは、いま冷蔵庫の中で実際にどこに入っているかを写す物。
--   ここで冷凍室の豚肉を勝手に '氷温' に書き換えると、
--   【データベースだけが嘘をつく】。誰も肉を移していないのに、
--   アプリは氷温ルームにあると表示する。
--
--   だから動かすのは、3 区分しか無かったせいで
--   【仕方なく嘘の場所に入れられていた行】だけにする。
--   具体的には、野菜室に入っているのに「冷蔵」としか書けなかった野菜。
--
--   肉・魚を氷温ルームへ移す話(下の 2-2)は、
--   人が実際にパックを移してから流す。
--
-- 【何度流しても壊れない理由】
--
--   どの update にも where location = '冷蔵' が付いている。
--   1 回目で '野菜' になった行は、2 回目には条件に当たらないので
--   もう触られない。
--   さらにこれは【後から人が直した場所を上書きしない】という意味も持つ。
--   例えば夏場にきゅうりを常温へ移した後でこのファイルを流し直しても、
--   きゅうりは常温のまま残る。

begin;

-- ------------------------------------------------------------
-- 2-1. 野菜室に入っている野菜を '野菜' へ(4 行)
-- ------------------------------------------------------------
-- 対象と根拠(取説 p.31 / 農研機構の最適貯蔵温度):
--
--   きゅうり … 低温障害を起こす代表格。0〜3℃ の冷蔵室では表面が
--               ピッティング(小さな凹み)を起こす。最適 10〜12℃ なので
--               本当は野菜室(4〜8℃)でも低いが、取説は「たて収納
--               スペース(4〜9℃・他より高め)に水気を拭いて立てて」
--               と名指ししている。5 区画の中ではここが最善。
--   小松菜  … 葉物。最適 0℃・湿度 95〜100%。温度だけなら冷蔵室でも
--               問題ないが、乾燥に弱いのでうるおいユニットのある
--               野菜室の下段に立てる方がもつ。
--   長ねぎ  … 最適 0〜2℃・湿度 95〜100%。同じく乾燥対策で野菜室。
--               においが強いのでラップをする(取説 p.19)。
--   人参    … 野菜室の下段/たて収納。葉が付いていたら落としてから。
--
-- 名前で探して id で探していない理由:
--   id は連番なので、将来シードを流し直すと番号がずれる。
--   品名なら、後から買い直した同じ野菜も同じ扱いになって都合がよい。
update inventory
   set location   = '野菜',
       updated_at = now()          -- 行が変わったことを端末に伝えるため
 where location = '冷蔵'
   and name in ('きゅうり', '小松菜', '長ねぎ', '人参');

-- ------------------------------------------------------------
-- 2-2.(実行しない)肉・魚を氷温ルームへ
-- ------------------------------------------------------------
-- いま肉・魚 4 点(豚ロースしゃぶしゃぶ用・生銀鮭・鶏もも肉・豚ひき肉)は
-- すべて冷凍室で【実際に凍っている】。凍った物を氷温ルームに入れることは
-- できないので、ここでは動かさない。
-- その結果、移行直後の「氷温」タブは 0 件になる。これは異常ではない。
--
-- 氷温ルームの使いどころ(取説 p.19 / p.24):
--   ・買ってきた肉・魚を凍らせずに置く。加熱調理用なら 7 日、
--     生食用(刺身)なら 3 日が日立の目安。
--   ・冷凍した肉・魚の【解凍場所】としても使える。
--     献立の前日にここへ移すのが本来の使い方。
--
-- ★ 実際にパックを氷温ルームへ移したときだけ、下の行の -- を外して流す。
--   (品名は移した物に合わせて書き換えること)
--
-- update inventory
--    set location   = '氷温',
--        updated_at = now()
--  where location = '冷凍'
--    and name in ('生銀鮭');

-- ------------------------------------------------------------
-- 2-3. あえて動かさない行と、その理由
-- ------------------------------------------------------------
--   玉ねぎ(常温のまま)
--     取説 p.31 は玉ねぎを「常温保存がおすすめの野菜」に分類している。
--     農研機構の数値でも最適【湿度 65〜70%】と低く、玉ねぎに悪いのは
--     低温より高湿度。野菜室は高湿度に作ってあるので、3 択の中では
--     むしろ一番勧めにくい。
--     ※ 引退した SQLite 側では「冷蔵」になっており、口頭では
--       「正解は野菜室」と言われていたが、取説の分類とは食い違う。
--       一次資料に従って常温のままにした。夏場に常温がつらい場合の
--       正しい逃がし先は一次資料では確認できなかったので、
--       ここでは判断せず人に委ねる。
--   キャベツ(カット)(冷蔵のまま)
--     カット済みなので切り口から傷む。最適 0℃・高湿度で、冷蔵室が適温。
--     カットした野菜は氷温ルームに入れてはいけない(取説 p.24)。
--   牛乳・6P チーズ・ヨーグルト・納豆(冷蔵のまま)
--     乳製品は氷温ルームに入れない(取説 p.24)。
--     納豆・豆腐は凍るとスが入るので同じく氷温は不可。
--   たまご(冷蔵のまま)
--     冷蔵室の小物ケースの卵スタンドに、とがった方を下にして置く
--     (取説 p.23)。ドアポケット(約 0〜7℃)は開け閉めで温度が動くので
--     定位置には向かない。
--   豚ロース・生銀鮭・鶏もも肉・豚ひき肉・讃岐うどん(冷凍のまま)
--     実際に凍っている。2-2 の通り。
--     なお讃岐うどんは取説 p.19 が冷凍室【上段】の例に挙げている。
--   カルピス(常温のまま)
--     未開封なら常温。開封後は表示に従って冷蔵へ。

commit;


-- ============================================================
-- 確認 — 実行後にここから下だけを選んで流す
-- ============================================================
-- 3 つとも想定どおりなら成功。1 つでも違ったら Part 1 から流し直す
-- (何度流しても壊れないので、そのまま全文を流し直してよい)。

-- 確認 1 — 新しい制約が入ったか
-- 「五区画になっている」が true なら成功。
-- 行が 1 つも返らない場合は制約が付いていない = Part 1 が通っていない。
select
  conname                                as 制約の名前,
  pg_get_constraintdef(oid)              as 制約の中身,
  pg_get_constraintdef(oid) like '%氷温%'
    and pg_get_constraintdef(oid) like '%野菜%'
                                         as 五区画になっている
  from pg_constraint
 where conrelid = 'public.inventory'::regclass
   and contype  = 'c'
   and conname  = 'inventory_location_check';

-- 確認 2 — 区画ごとの件数
-- 想定(2026-08-09 時点の 18 行を移行した直後):
--     冷蔵 7 / 氷温 0 / 野菜 4 / 冷凍 5 / 常温 2   合計 18
-- 氷温が 0 件なのは正常(2-2 の通り、肉・魚は全部まだ冷凍室にある)。
-- 0 件の区画も行として出るように、5 区画の一覧側から結合している。
-- (単に group by すると、0 件の区画は行ごと消えて「無い」のか
--  「0 件」なのか区別が付かない)
select
  v.区画,
  coalesce(i.件数, 0) as 件数
  from (values (1, '冷蔵'), (2, '氷温'), (3, '野菜'), (4, '冷凍'), (5, '常温'))
       as v(並び順, 区画)
  left join (select location, count(*) as 件数
               from inventory
              group by location) as i
    on i.location = v.区画
 order by v.並び順;

-- 確認 3 — 振り分け漏れが 0 件か
-- 4 つの数字が【すべて 0】なら漏れなし。
-- 最後の「全部で何行あるか」は 18 が想定(在庫を足し引きしていれば変わる)。
select
  (select count(*) from inventory
    where location is null)                                as 場所が空の行,
  (select count(*) from inventory
    where location not in ('冷蔵','氷温','野菜','冷凍','常温'))
                                                           as 五区画に無い値の行,
  (select count(*) from inventory
    where location = '冷蔵'
      and name in ('きゅうり','小松菜','長ねぎ','人参'))    as 野菜室へ移し忘れ,
  (select count(*) from inventory
    where location = '氷温'
      and name in ('6Pチーズ','明治ブルガリアヨーグルト','牛乳',
                   '納豆(おろしだれ)','納豆(金のつぶ たれ)',
                   'キャベツ(カット)'))                    as 氷温に入れてはいけない物,
  (select count(*) from inventory)                         as 全部で何行あるか;

